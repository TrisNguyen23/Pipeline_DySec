# Public tracer
# ============================================================================

class LocalPackageTracer:
    """
    DySec-style tracer for locally generated packages.

    Architecture:

        generated package
                |
                v
        fresh workspace
                |
                v
        fresh virtualenv
                |
                v
        deploy package
                |
                v
        start 5 bpftrace probes
                |
                v
        pip install
                |
                +----> install.trace
                |
                v
        observe behaviour
                |
                v
        stop probes
                |
                v
        5 bpftrace traces
                |
                v
        6 trace families total

    This class deliberately does NOT know about:

        strategy_A
        strategy_B
        strategy_C
        round
        evasion
        DySec prediction

    Those belong to the robustness pipeline.
    """

    def __init__(
        self,
        trace_output_dir: Path = DEFAULT_TRACE_OUTPUT,
        probe_dir: Path = TRACE_ENGINE_DIR,
        sandbox_user: str = "dysec",
        post_install_window: int = 120,
        install_timeout: int = 180,
    ):

        self.trace_output_dir = Path(
            trace_output_dir
        )

        self.probe_dir = Path(
            probe_dir
        )

        self.sandbox_user = sandbox_user

        self.post_install_window = (
            post_install_window
        )

        self.install_timeout = (
            install_timeout
        )

        require_root()

        check_command(
            "bpftrace"
        )

        check_command(
            "python3"
        )

        validate_probe_files(
            self.probe_dir
        )

        (
            self.sandbox_uid,
            self.sandbox_gid,
        ) = resolve_sandbox_user(
            sandbox_user
        )

    def trace(
        self,
        package_dir: str | Path,
        trace_name: Optional[str] = None,
    ) -> TraceResult:
        """
        Trace exactly one package once.

        Retry/round logic belongs outside this class.
        """

        package_dir = Path(
            package_dir
        ).resolve()

        if not package_dir.exists():

            raise FileNotFoundError(
                f"Package directory does not exist: "
                f"{package_dir}"
            )

        if not package_dir.is_dir():

            raise NotADirectoryError(
                f"Package path is not a directory: "
                f"{package_dir}"
            )

        if trace_name is None:

            trace_name = package_dir.name

        trace_root = (
            self.trace_output_dir
            / trace_name
        )

        if trace_root.exists():

            shutil.rmtree(
                trace_root,
                ignore_errors=True,
            )

        trace_root.mkdir(
            parents=True,
            exist_ok=True,
        )

        os.chown(
            trace_root,
            self.sandbox_uid,
            self.sandbox_gid,
        )

        work_dir = (
            trace_root
            / "workspace"
        )

        print()
        print(
            "=" * 70
        )

        print(
            "DYSEC TRACE"
        )

        print(
            "=" * 70
        )

        print(
            f"Package: {package_dir}"
        )

        print(
            f"Output:  {trace_root}"
        )

        print(
            "=" * 70
        )

        result = trace_package(
            package_dir=package_dir,
            trace_dir=trace_root,
            work_dir=work_dir,
            uid=self.sandbox_uid,
            gid=self.sandbox_gid,
            probe_dir=self.probe_dir,
            post_install_window=self.post_install_window,
            install_timeout=self.install_timeout,
        )

        return result


