def main() -> int:

    parser = argparse.ArgumentParser(
        description=(
            "Run one DySec-style dynamic trace extraction "
            "on a local Python package."
        )
    )

    parser.add_argument(
        "package_dir",
        help=(
            "Path to the local Python package directory."
        ),
    )

    parser.add_argument(
        "--output",
        default=str(
            DEFAULT_TRACE_OUTPUT
        ),
        help=(
            "Directory where traces are stored."
        ),
    )

    parser.add_argument(
        "--probe-dir",
        default=str(
            TRACE_ENGINE_DIR
        ),
        help=(
            "Directory containing the five .bt probe files."
        ),
    )

    parser.add_argument(
        "--sandbox-user",
        default="dysec",
        help=(
            "Linux user used for package deployment "
            "and installation."
        ),
    )

    parser.add_argument(
        "--window",
        type=int,
        default=120,
        help=(
            "Post-install observation window in seconds."
        ),
    )

    parser.add_argument(
        "--install-timeout",
        type=int,
        default=180,
        help=(
            "Maximum package installation time in seconds."
        ),
    )

    parser.add_argument(
        "--trace-name",
        default=None,
        help=(
            "Name of the trace output directory."
        ),
    )

    args = parser.parse_args()

    try:

        tracer = LocalPackageTracer(
            trace_output_dir=Path(
                args.output
            ),

            probe_dir=Path(
                args.probe_dir
            ),

            sandbox_user=args.sandbox_user,

            post_install_window=(
                args.window
            ),

            install_timeout=(
                args.install_timeout
            ),
        )

        result = tracer.trace(
            package_dir=args.package_dir,
            trace_name=args.trace_name,
        )

    except Exception as exc:

        print(
            f"[x] {type(exc).__name__}: {exc}",
            file=sys.stderr,
        )

        return 1

    # =========================================================================
    # Final result
    # =========================================================================

    print()
    print(
        "=" * 70
    )

    print(
        "TRACE RESULT"
    )

    print(
        "=" * 70
    )

    print(
        f"Package:          {result.package_dir}"
    )

    print(
        f"Trace directory:  {result.trace_dir}"
    )

    print(
        f"Deploy success:   {result.deploy_success}"
    )

    print(
        f"Install success:  {result.install_success}"
    )

    print(
        f"Install return:   {result.install_return_code}"
    )

    print(
        f"Trace available:  {result.trace_available}"
    )

    print(
        f"Valid trace:      {result.valid_trace}"
    )

    print(
        f"Partial trace:    {result.partial_trace}"
    )

    print(
        f"Duration:         "
        f"{result.duration_seconds:.2f}s"
    )

    print()

    print(
        "Trace families:"
    )

    for family in TRACE_FAMILIES:

        path = result.trace_files.get(
            family
        )

        if path:

            size = Path(path).stat().st_size

            print(
                f"  {family:20s} "
                f"{size:10d} bytes  {path}"
            )

        else:

            print(
                f"  {family:20s} "
                f"MISSING"
            )

    if result.probe_errors:

        print()

        print(
            "Trace / probe errors:"
        )

        for error in result.probe_errors:

            print(
                f"  - {error}"
            )

    if result.notes:

        print()

        print(
            f"Notes: {result.notes}"
        )

    print(
        "=" * 70
    )

    # The caller must inspect valid_trace.
    # A failed package installation is not a tracer crash.
    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )